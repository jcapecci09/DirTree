from pathlib import Path
import argparse


def get_directory_structure(path: Path, depth: int = 0, max_depth: int = 3, show_hidden: bool = False) -> list[dict | str]:
    """Gets the directory structure and stores it in a nested list/dictionary.

    :param path: Path to the directory being inspected
    :param depth: Current directory depth, defaults to 0
    :param max_depth: Maximum directory depth to inspect, defaults to 3
    :return: Directory tree represented as a list of dictionaries and strings
    """

    structure = []

    # Iterate through every item in the current directory
    for item in path.iterdir():

        # Ignore hidden files and directories (e.g., .git, .gitignore)
        if item.name.startswith('.') and not show_hidden:
            continue

        # If the item is a file, append its name to the directory structure

  
        if item.is_file():
            structure.append(item.name)

        # If the item is a directory, determine whether to inspect its contents
        elif item.is_dir():

            # If the maximum depth has not been reached, recursively inspect the directory
            if depth < max_depth:
                structure.append({
                    item.name: get_directory_structure(item, depth + 1, max_depth, show_hidden)
                })

            # If the maximum depth has been reached, append only the directory name
            else:
                structure.append({item.name: []})

    # Return the completed directory structure
    return structure


def print_directory_structure(structure, indent=0):
    """Prints a nested directory structure with indentation and file/folder icons.

    :param structure: Directory structure generated by get_directory_structure()
    :param indent: Current indentation level, defaults to 0
    """

    # Iterate through each file or directory in the structure
    for item in structure:

        # If the item is a dictionary, it represents a directory and its contents
        if isinstance(item, dict):
            for folder, contents in item.items():

                # Print the directory name at the current indentation level
                print('    ' * indent + f'📁 {folder}/')

                # Recursively print the directory's contents at the next indentation level
                print_directory_structure(contents, indent + 1)

        # Otherwise, the item is a file or a directory at the maximum depth
        else:
            print('    ' * indent + f'📄 {item}')


def write_directory_structure(structure, output, indent=0):
    """Writes the directory structure to a text file.

    :param structure: Directory structure generated by get_directory_structure()
    :param output: Output file path
    :param indent: Initial indentation level, defaults to 0
    """

    # Open the output file in write mode using UTF-8 encoding
    if indent == 1:
        with open(output, 'a', encoding='utf-8') as o:

            # Write the directory structure using the opened file
            _write_structure(structure, o, indent)

    # If an indentation level was provided, continue writing to the existing file object
    else:
        _write_structure(structure, output, indent)


def _write_structure(structure, o, indent):
    """Recursively writes directory names and file names to an open file.

    :param structure: Directory structure to write
    :param f: Open file object
    :param indent: Current indentation level
    """

    # Iterate through each item in the directory structure
    for item in structure:

        # If the item is a dictionary, it represents a directory and its contents
        if isinstance(item, dict):
            for folder, contents in item.items():


                # Write the directory name at the current indentation level
                o.write('    ' * indent + f'📁 {folder}/\n')

                # Recursively write the directory contents at the next indentation level
                _write_structure(contents, o, indent + 1)

        # Otherwise, write the file or directory name
        else:
            o.write('    ' * indent + f'📄 {item}\n')


def main():

    # Set up parser
    parser = argparse.ArgumentParser(description='Returns text file of directory structure')

    # Set arguements for parser
    parser.add_argument('-i', '--input', help='directory path to find structure of', required=False, default=Path.cwd())
    parser.add_argument('-o', '--output', help='Output text file name', required=False, default='dir.txt')
    parser.add_argument('-d', '--depth', help='Max Depth to find structure', required=False, default=2, type=int)
    parser.add_argument('--print', required=False, action='store_true', help='Print to terminal')
    parser.add_argument('--show_hidden', required=False, action='store_true', help='Show hidden folders')

    # Grab arguements
    args = parser.parse_args()

    # Get the current working directory
    cwd = Path(args.input)

    # Print the root directory name
    if args.print:
        print(f'📁 {cwd.name}/')

    # Generate the directory structure, inspecting up to two levels deep
    structure = get_directory_structure(cwd, max_depth=args.depth, show_hidden=args.show_hidden)

    # Write cwd to output
    with open(args.output, 'w') as f:
        f.write(f'📁 {cwd.name}/\n')

    # Print the directory structure to the terminal, starting at indentation level 1
    if args.print:
        print_directory_structure(structure, indent=1)

    # Write the directory structure to output
    write_directory_structure(structure, args.output, indent=1)


# Execute main() only when this script is run directly
if __name__ == '__main__':
    main()
